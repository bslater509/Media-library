  // Thumbnail size presets. Each level scales the justified row height, so
  // larger presets yield fewer, bigger tiles and smaller presets more, smaller
  // ones. Persisted per browser.
  export const TILE_SCALES = [0.6, 0.8, 1.0, 1.25, 2.0];
  export const TILE_SCALE_LABELS = ['XS', 'S', 'M', 'L', 'XL'];
  export const TILE_SCALE_KEY = 'lib_tile_scale';
  export function loadTileScale() {
    try {
      const v = parseFloat(localStorage.getItem(TILE_SCALE_KEY));
      const idx = TILE_SCALES.indexOf(v);
      return idx >= 0 ? TILE_SCALES[idx] : 1.0;
    } catch (e) {
      return 1.0;
    }
  }

  export const SIDEBAR_TREE_KEY = 'lib_sidebar_tree_expanded';

  export function loadExpandedFolders() {
    try {
      const raw = localStorage.getItem(SIDEBAR_TREE_KEY);
      if (!raw) return new Set();
      const arr = JSON.parse(raw);
      return new Set(Array.isArray(arr) ? arr : []);
    } catch (e) {
      return new Set();
    }
  }

  export function persistExpandedFolders(set) {
    try {
      localStorage.setItem(SIDEBAR_TREE_KEY, JSON.stringify([...set]));
    } catch (e) { /* ignore quota/security errors */ }
  }

  export const ANIMATED_THUMBS_KEY = 'lib_animated_thumbs';

  export function loadAnimatedThumbs() {
    try {
      return localStorage.getItem(ANIMATED_THUMBS_KEY) === 'true';
    } catch (e) {
      return false;
    }
  }

  export function persistAnimatedThumbs(val) {
    try {
      localStorage.setItem(ANIMATED_THUMBS_KEY, val ? 'true' : 'false');
    } catch (e) { /* ignore */ }
  }

